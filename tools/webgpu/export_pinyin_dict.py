"""Plan 03 step 4 (D3): pypinyin's dictionaries, reduced to what lazy_pinyin(heteronym=False) reads.

  .venv313\\Scripts\\python.exe tools/webgpu/export_pinyin_dict.py

Writes web/src/text/pinyin_dict.txt, read by web/src/text/pinyin.ts, and copies pypinyin's licence (MIT)
next to it. Lines starting with # are comments. Every other line is `key<TAB>readings`:
  - a key of one character is a PINYIN_DICT entry, with its first reading (pypinyin splits on ",");
  - a longer key is a PHRASES_DICT entry, with the first reading of each character, space-separated.
Only first readings are kept: with heteronym=False, the converter and tone sandhi read only x[0].
The readings keep pypinyin's tone marks; pinyin.ts converts them as pypinyin does.
"""

from __future__ import annotations

import hashlib
import shutil
from importlib.metadata import distribution, version
from pathlib import Path

from pypinyin.constants import PHRASES_DICT, PINYIN_DICT, RE_HANS


REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "web/src/text/pinyin_dict.txt"
LICENSE_OUT = REPO / "web/src/text/pinyin_dict.LICENSE.txt"


def main() -> None:
    lines: list[str] = []
    for cp in sorted(PINYIN_DICT):
        reading = PINYIN_DICT[cp].split(",")[0]
        assert RE_HANS.match(chr(cp)) and reading and " " not in reading, hex(cp)
        lines.append(f"{chr(cp)}\t{reading}")
    for word in sorted(PHRASES_DICT):
        readings = [items[0] for items in PHRASES_DICT[word]]
        # pinyin.ts relies on these: phrases are longer than one character, all Han, one reading per character
        assert len(word) > 1 and RE_HANS.match(word) and len(readings) == len(word), word
        assert all(r and " " not in r for r in readings), word
        lines.append(f"{word}\t{' '.join(readings)}")
    body = "\n".join(lines) + "\n"
    header = (
        f"# pypinyin {version('pypinyin')}: PINYIN_DICT and PHRASES_DICT, first readings only. MIT licence,"
        f" see pinyin_dict.LICENSE.txt.\n# Generated by tools/webgpu/export_pinyin_dict.py; body sha256"
        f" {hashlib.sha256(body.encode()).hexdigest()}\n"
    )
    OUT.write_bytes((header + body).encode("utf-8"))
    licence = next(f for f in distribution("pypinyin").files or [] if f.name.upper().startswith("LICENSE"))
    shutil.copyfile(Path(str(licence.locate())), LICENSE_OUT)
    print(f"{len(PINYIN_DICT)} characters, {len(PHRASES_DICT)} phrases -> {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
